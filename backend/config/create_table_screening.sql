-- ============================================================
-- Table: application_screenings
-- One generic screening table for research-permit and ethics apps.
-- All IDs in KEPK use BIGINT / INT8.
-- ============================================================
CREATE TABLE IF NOT EXISTS application_screenings (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id  BIGINT UNIQUE NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  screening_type  VARCHAR(30) NOT NULL,
  answers         JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at      TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_screening_type CHECK (screening_type IN ('RESEARCH', 'ETHICS'))
);

CREATE INDEX IF NOT EXISTS idx_application_screenings_application_id
  ON application_screenings(application_id);

CREATE INDEX IF NOT EXISTS idx_application_screenings_type
  ON application_screenings(screening_type);
