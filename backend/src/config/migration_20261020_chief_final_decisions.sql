-- KEPK: support five final decision categories from CHIEF_KEPK.
-- Run once against the active Penma/KEPK PostgreSQL database.
BEGIN;

ALTER TABLE applications DROP CONSTRAINT IF EXISTS chk_status;
ALTER TABLE applications ADD CONSTRAINT chk_status CHECK (status IN (
  'DRAFT','SUBMITTED','ADMIN_REVIEW','REVISION_REQUIRED','ADMIN_APPROVED',
  'SEKRETARIS_REVIEW','WAITING_REVIEWER','UNDER_REVIEW','REVIEW_COMPLETED',
  'APPROVED','REJECTED','NOT_ASSESSABLE','PERMIT_ISSUED'
));

ALTER TABLE final_decisions DROP CONSTRAINT IF EXISTS chk_decision;
ALTER TABLE final_decisions ADD CONSTRAINT chk_decision CHECK (decision IN (
  'APPROVED','APPROVED_MINOR','MAJOR_REVISION','REJECTED','NOT_ASSESSABLE','REVISION_REQUIRED'
));

COMMIT;
